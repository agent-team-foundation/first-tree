import { spawn } from "node:child_process";
import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const WEB_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const AUTHORING_SOURCE = join(WEB_ROOT, "orientation-videos", "chapters.json");
const VOICEOVER_OUTPUT = join(WEB_ROOT, "orientation-videos", "voiceover");
const VOICEOVER_SCRIPT_OUTPUT = join(WEB_ROOT, "orientation-videos", "voiceover-script.md");
const CAPTIONS_OUTPUT = join(WEB_ROOT, "public", "onboarding", "orientation");
const PIPER_MODEL = process.env.ORIENTATION_PIPER_MODEL;
const CHECK_ONLY = process.argv.includes("--check");
const WRITE_TEXT_ONLY = process.argv.includes("--write-text");

if (!CHECK_ONLY && !WRITE_TEXT_ONLY && !PIPER_MODEL) {
  throw new Error("Set ORIENTATION_PIPER_MODEL to an approved Piper ONNX voice model");
}

const AUTHORING = JSON.parse(await readFile(AUTHORING_SOURCE, "utf8"));
const CHAPTERS = AUTHORING.chapters;

function validateAuthoringSource() {
  if (!CHAPTERS || typeof CHAPTERS !== "object") throw new Error("chapters.json must define chapters");
  for (const [id, chapter] of Object.entries(CHAPTERS)) {
    if (!chapter || typeof chapter !== "object") throw new Error(`${id} must be an object`);
    if (typeof chapter.title !== "string" || chapter.title.trim() === "") throw new Error(`${id} needs a title`);
    if (!Number.isFinite(chapter.durationInSeconds) || chapter.durationInSeconds <= 0) {
      throw new Error(`${id} needs a positive durationInSeconds`);
    }
    if (!Array.isArray(chapter.cues) || chapter.cues.length === 0) throw new Error(`${id} needs narration cues`);
    let previousEnd = 0;
    for (const [index, cue] of chapter.cues.entries()) {
      if (!Array.isArray(cue) || cue.length !== 3) throw new Error(`${id} cue ${index + 1} must be [start, end, text]`);
      const [start, end, text] = cue;
      if (!Number.isFinite(start) || !Number.isFinite(end) || start < previousEnd || end <= start) {
        throw new Error(`${id} cue ${index + 1} has invalid or overlapping timing`);
      }
      if (end > chapter.durationInSeconds) throw new Error(`${id} cue ${index + 1} exceeds the chapter duration`);
      if (typeof text !== "string" || text.trim() === "") throw new Error(`${id} cue ${index + 1} needs text`);
      previousEnd = end;
    }
  }
}

function run(command, args, { input, label = command } = {}) {
  return new Promise((resolvePromise, rejectPromise) => {
    const child = spawn(command, args, { stdio: [input === undefined ? "ignore" : "pipe", "pipe", "pipe"] });
    let stderr = "";
    child.stderr.on("data", (chunk) => {
      stderr += chunk.toString();
    });
    child.once("error", rejectPromise);
    child.once("exit", (code) => {
      if (code === 0) resolvePromise();
      else rejectPromise(new Error(`${label} exited with code ${code}\n${stderr}`));
    });
    if (input !== undefined) child.stdin.end(input);
  });
}

async function mediaDuration(path) {
  const child = spawn(
    "ffprobe",
    ["-v", "error", "-show_entries", "format=duration", "-of", "default=nw=1:nk=1", path],
    { stdio: ["ignore", "pipe", "pipe"] },
  );
  let stdout = "";
  let stderr = "";
  child.stdout.on("data", (chunk) => {
    stdout += chunk.toString();
  });
  child.stderr.on("data", (chunk) => {
    stderr += chunk.toString();
  });
  await new Promise((resolvePromise, rejectPromise) => {
    child.once("error", rejectPromise);
    child.once("exit", (code) => {
      if (code === 0) resolvePromise();
      else rejectPromise(new Error(`ffprobe exited with code ${code}\n${stderr}`));
    });
  });
  const duration = Number.parseFloat(stdout.trim());
  if (!Number.isFinite(duration)) throw new Error(`Invalid audio duration for ${path}: ${stdout.trim()}`);
  return duration;
}

function timestamp(seconds) {
  const milliseconds = Math.round(seconds * 1000);
  const minutes = Math.floor(milliseconds / 60_000);
  const remainingSeconds = Math.floor((milliseconds % 60_000) / 1000);
  const remainingMilliseconds = milliseconds % 1000;
  return `00:${String(minutes).padStart(2, "0")}:${String(remainingSeconds).padStart(2, "0")}.${String(remainingMilliseconds).padStart(3, "0")}`;
}

function vttFor(cues) {
  const blocks = cues.map(([start, end, text]) => `${timestamp(start)} --> ${timestamp(end)}\n${text}`);
  return `WEBVTT\n\n${blocks.join("\n\n")}\n`;
}

function voiceoverScriptFor() {
  const lines = [
    "# Orientation voiceover script",
    "",
    "Generated from `chapters.json`. Do not edit this file directly.",
    "",
    "The narration is intentionally sparse: it explains the product idea while the viewer watches the real interface. There is no music or decorative sound. Closed captions reproduce these spoken lines and are off by default.",
    "",
    `The committed authoring tracks in \`voiceover/\` use Piper's \`${AUTHORING.voice.model}\` ${AUTHORING.voice.description} voice. Its ${AUTHORING.voice.trainingDataset} training dataset is ${AUTHORING.voice.trainingDatasetLicense}. Each finished track is mono AAC, targeted to -16 LUFS, and padded to the exact chapter duration.`,
  ];
  for (const chapter of Object.values(CHAPTERS)) {
    lines.push("", `## ${chapter.title}`, "", "| Time | Narration |", "| --- | --- |");
    for (const [start, end, text] of chapter.cues) {
      lines.push(`| ${timestamp(start)}–${timestamp(end)} | ${text.replaceAll("|", "\\|")} |`);
    }
  }
  return `${lines.join("\n")}\n`;
}

async function syncTextOutputs({ check }) {
  const expectedFiles = [
    [VOICEOVER_SCRIPT_OUTPUT, voiceoverScriptFor()],
    ...Object.entries(CHAPTERS).map(([id, chapter]) => [join(CAPTIONS_OUTPUT, `${id}.vtt`), vttFor(chapter.cues)]),
  ];
  for (const [path, expected] of expectedFiles) {
    if (check) {
      const actual = await readFile(path, "utf8");
      if (actual !== expected) throw new Error(`${path} is stale; run video:voiceover:write-text`);
    } else {
      await writeFile(path, expected);
    }
  }
}

async function renderChapter(id, chapter, temporaryDirectory) {
  const segments = [];
  for (const [index, [start, end, text]] of chapter.cues.entries()) {
    const segmentPath = join(temporaryDirectory, `${id}-${index}.wav`);
    await run(
      "uv",
      [
        "tool",
        "run",
        "--python",
        "3.12",
        "--from",
        "piper-tts",
        "piper",
        "--model",
        PIPER_MODEL,
        "--output-file",
        segmentPath,
        "--length-scale",
        "0.92",
        "--sentence-silence",
        "0.12",
      ],
      { input: `${text}\n`, label: `Piper (${id} cue ${index + 1})` },
    );
    const duration = await mediaDuration(segmentPath);
    const available = end - start;
    if (duration > available) {
      throw new Error(
        `${id} cue ${index + 1} is ${duration.toFixed(2)}s but only ${available.toFixed(2)}s is available`,
      );
    }
    segments.push({ path: segmentPath, start });
  }

  const inputs = segments.flatMap(({ path }) => ["-i", path]);
  const delayed = segments.map(
    ({ start }, index) => `[${index}:a]adelay=${Math.round(start * 1000)}:all=1[voice${index}]`,
  );
  const voices = segments.map((_, index) => `[voice${index}]`).join("");
  const filter = [
    ...delayed,
    `${voices}amix=inputs=${segments.length}:normalize=0,apad=whole_dur=${chapter.durationInSeconds},atrim=duration=${chapter.durationInSeconds},loudnorm=I=-16:LRA=7:TP=-1.5[aout]`,
  ].join(";");
  const outputPath = join(VOICEOVER_OUTPUT, `${id}.m4a`);
  await run(
    "ffmpeg",
    [
      "-y",
      ...inputs,
      "-filter_complex",
      filter,
      "-map",
      "[aout]",
      "-c:a",
      "aac",
      "-b:a",
      "96k",
      "-ar",
      "48000",
      "-ac",
      "1",
      outputPath,
    ],
    { label: `ffmpeg (${id})` },
  );
  process.stdout.write(`${id}: ${chapter.durationInSeconds}s voiceover written\n`);
}

async function main() {
  validateAuthoringSource();
  await mkdir(CAPTIONS_OUTPUT, { recursive: true });
  await syncTextOutputs({ check: CHECK_ONLY });
  if (CHECK_ONLY) {
    process.stdout.write("Orientation voiceover source, review script, and captions are synchronized\n");
    return;
  }
  if (WRITE_TEXT_ONLY) {
    process.stdout.write("Orientation voiceover review script and captions written\n");
    return;
  }
  await mkdir(VOICEOVER_OUTPUT, { recursive: true });
  const temporaryDirectory = await mkdtemp(join(tmpdir(), "first-tree-orientation-voiceover-"));
  try {
    for (const [id, chapter] of Object.entries(CHAPTERS)) {
      await renderChapter(id, chapter, temporaryDirectory);
    }
  } finally {
    await rm(temporaryDirectory, { recursive: true, force: true });
  }
}

await main();
